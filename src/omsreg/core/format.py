"""Форматирование значений под русскую локаль для отчётов.

Обратная сторона omsreg.core.convert: там строка -> число (разбор полей DBF),
здесь число или момент времени -> строка для человека и Excel. Ничего доменного
(стационар/ОМС) тут нет, поэтому примитивы живут в core и переиспользуются всеми
отчётами.
"""

from __future__ import annotations

from datetime import datetime


def money(x) -> str:
    """Денежная сумма с пробелом как разделителем тысяч: 1 234 567.89."""
    return f"{x:,.2f}".replace(",", " ")


def csv_num(x) -> str:
    """Число для CSV с десятичной запятой (русский Excel; разделитель полей — ';')."""
    return f"{x:.2f}".replace(".", ",")


def pct(part, total) -> str:
    """Доля в процентах, выровненная по ширине: ' 42.0%'. total=0 -> '  0.0%'."""
    return f"{part / total * 100:5.1f}%" if total else "  0.0%"


def report_stamp(*, seconds: bool = True) -> str:
    """Момент формирования отчёта для шапки: «25.07.2026 14:30:05».

    seconds=False — то же без секунд; так подписаны HTML-формы всех отчётов,
    текстовые формы пишут время с секундами. Одна запись формата на все отчёты.
    """
    return datetime.now().strftime("%d.%m.%Y %H:%M:%S" if seconds else "%d.%m.%Y %H:%M")
