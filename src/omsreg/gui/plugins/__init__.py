"""Плагины утилит. Каждый модуль объявляет объект SPEC (omsreg.gui.spec.UtilitySpec).

В этом пакете лежат ТОЛЬКО модули-плагины: один файл — одна вкладка. Общий код вкладок
живёт уровнем выше, рядом с платформой (omsreg.gui.plugin_fields), а доменные значения
и функции — в omsreg.utils; здесь их не дублируют.

Встроенные плагины импортируются здесь ЯВНО (кортеж BUILTIN): это гарантирует, что
они попадают в сборку PyInstaller (.exe) и находятся там — динамический скан
pkgutil.iter_modules в замороженном onefile-приложении не видит модулей и возвращал
бы пустой список (из-за этого в exe не было ни одной утилиты).

Дополнительно omsreg.gui.registry.discover() досканирует эту папку на предмет
других модулей — так при запуске из исходников новую утилиту всё ещё можно добавить
одним файлом. Для распространения через exe добавьте новый плагин и в BUILTIN.
"""

